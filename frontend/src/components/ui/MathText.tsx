interface MathTextProps {
  text: string;
  className?: string;
  as?: 'span' | 'div' | 'p' | 'h1' | 'h2' | 'h3' | 'h4' | 'h5' | 'h6' | 'label';
  block?: boolean;
  dir?: 'auto' | 'ltr' | 'rtl';
}

/**
 * HTML entity escaper to guarantee zero unescaped HTML/XML injection into DOM.
 */
function escapeHtml(str: string): string {
  if (!str) return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

/**
 * Clean up common OCR, ingestion quirks, and collapsed JSON escape artifacts in LaTeX formulas.
 */
function cleanLatex(formula: string): string {
  if (!formula) return '';
  let s = formula.trim();

  // Repair collapsed LaTeX commands caused by JSON escape collision (\t, \r, \f)
  s = s.replace(/(?:[\t\x09]|\b)ext\{/g, '\\text{');
  s = s.replace(/(?:[\r\x0d]|\b)ightarrow\b/g, '\\rightarrow ');
  s = s.replace(/(?:[\x0c]|\b)rac\{/g, '\\frac{');
  s = s.replace(/(?:[\t\x09]|\b)imes\b/g, '\\times ');
  s = s.replace(/(?:[\t\x09]|\b)heta\b/g, '\\theta ');
  s = s.replace(/(?:[\r\x0d]|\b)ho\b/g, '\\rho ');
  s = s.replace(/(?:[\r\x0d]|\b)ight\b/g, '\\right');
  s = s.replace(/(?:[\r\x0d]|\b)xrightarrow\b/g, '\\xrightarrow ');
  s = s.replace(/\bce\{/g, '\\ce{');

  // Normalize reaction arrows and dashes
  s = s.replace(/→/g, '\\rightarrow ').replace(/⇌/g, '\\rightleftharpoons ');
  s = s.replace(/[–—]/g, '-');

  // Fix OCR pipe mistaken for closing bracket
  s = s.replace(/\|(\s*\\?(?:left)?\s*\()/g, ']$1');
  s = s.replace(/\|(?=\s*[+\-=→\\])/g, ']');

  // Clean trailing equation labels generated by OCR (e.g., \qquad (1))
  s = s.replace(/\\mathrm\{[q\s]*quad\s*\([0-9.]+\)\s*\}\s*\\right\)?\s*$/i, '');
  s = s.replace(/\\[q]?quad\s*\([0-9.]+\s*\\right\)?\s*$/i, '');
  s = s.replace(/\\[q]?quad\s*\([0-9.]+\)\s*$/i, '');

  return s;
}

/**
 * Safely render a LaTeX segment using KaTeX with HTML-escaped fallback to prevent DOM pollution.
 */
function renderKatexHtml(math: string, displayMode: boolean): string {
  try {
    const cleaned = cleanLatex(math);
    return katex.renderToString(cleaned, {
      displayMode,
      throwOnError: false,
      output: 'htmlAndMathml',
      strict: false,
      trust: false,
    });
  } catch (err) {
    console.warn('KaTeX rendering error:', err);
    // Escape HTML to prevent broken tags (<noscript>, <script>) from corrupting DOM
    return `<span class="katex-fallback font-mono text-xs">${escapeHtml(math)}</span>`;
  }
}

/**
 * Renders plain text with code block, inline code, and structured Markdown table formatting.
 */
function renderTextWithMarkdownElements(text: string, keyPrefix: string): React.ReactNode[] {
  if (!text) return [];

  // Match:
  // 1. Fenced code blocks ```lang\ncode\n```
  // 2. Inline code `...`
  // 3. Markdown tables: continuous rows starting and ending with pipes including a divider row | --- |
  const parts = text.split(/(```[\s\S]*?```|`[^`\n]+?`|(?:(?:^|\n)[ \t]*\|[^\n]+\|[ \t]*(?:\r?\n[ \t]*\|(?:\s*:?-+:?\s*\|)+)+(?:\r?\n[ \t]*\|[^\n]+\|[ \t]*)+))/g);

  return parts.map((part, pIdx) => {
    if (!part) return null;

    // Fenced code block ```...```
    if (part.startsWith('```') && part.endsWith('```') && part.length >= 6) {
      const inner = part.slice(3, -3);
      const firstLineMatch = inner.match(/^([a-zA-Z0-9_-]+)\r?\n/);
      const lang = firstLineMatch ? firstLineMatch[1].toLowerCase() : '';
      const codeContent = lang ? inner.replace(/^[a-zA-Z0-9_-]+\r?\n/, '').trim() : inner.trim();

      // 1. Chemical Structure / SMILES rendering
      if (lang === 'smiles' || lang === 'chemical') {
        return (
          <ChemicalStructure
            key={`${keyPrefix}-chem-${pIdx}`}
            smiles={codeContent}
            className="my-2"
          />
        );
      }

      // 2. Biological Cladogram / Taxonomic Tree rendering
      if (lang === 'cladogram' || lang === 'taxonomy' || lang === 'tree') {
        return (
          <CladogramTree
            key={`${keyPrefix}-clado-${pIdx}`}
            content={codeContent}
            className="my-2"
          />
        );
      }

      // 3. Geographic & Spatial Map Work rendering
      if (lang === 'mapwork' || lang === 'map') {
        const lines = codeContent.split(/\r?\n/).filter(l => l.trim().length > 0);
        return (
          <GeographyMapWork
            key={`${keyPrefix}-map-${pIdx}`}
            features={lines.length > 0 ? lines : undefined}
            className="my-2"
          />
        );
      }

      return (
        <pre
          key={`${keyPrefix}-code-block-${pIdx}`}
          className="my-2 p-2.5 bg-gray-50 print:bg-gray-100/80 border border-gray-200 rounded font-mono text-xs overflow-x-auto whitespace-pre text-left block text-gray-900"
        >
          <code>{codeContent}</code>
        </pre>
      );
    }

    // Inline code block `...`
    if (part.startsWith('`') && part.endsWith('`') && part.length >= 2) {
      const codeContent = part.slice(1, -1);
      return (
        <code
          key={`${keyPrefix}-code-inline-${pIdx}`}
          className="px-1.5 py-0.5 bg-gray-100 print:bg-gray-100/90 border border-gray-200 rounded font-mono text-xs text-indigo-700 print:text-black font-semibold"
        >
          {codeContent}
        </code>
      );
    }

    // Structured Markdown Table (Financial Journals, Ledgers, Accounting, Scientific Data)
    if (part.trim().startsWith('|') && part.includes('\n') && /\|(?:\s*:?-+:?\s*\|)+/.test(part)) {
      const lines = part.trim().split(/\r?\n/).filter((l) => l.trim().length > 0);
      if (lines.length >= 2) {
        const parseRow = (line: string) => {
          const trimmed = line.trim().replace(/^\|/, '').replace(/\|$/, '');
          return trimmed.split('|').map((c) => c.trim());
        };
        const headers = parseRow(lines[0]);
        const sepIdx = lines.findIndex((l, idx) => idx > 0 && /^\s*\|?(?:\s*:?-+:?\s*\|)+\s*$/.test(l));
        const dataLines = sepIdx !== -1 ? lines.slice(sepIdx + 1) : lines.slice(1);
        const dataRows = dataLines.map(parseRow);

        // Check for Accounting Journal or Ledger modalities
        const isJournal = headers.some((h) => /debit|credit|l\.?f\.?/i.test(h));
        const isLedger =
          headers.some((h) => /\b(dr|cr)\b/i.test(h)) ||
          (headers.length >= 6 && headers.filter((h) => /particulars/i.test(h)).length >= 2);

        return (
          <div key={`${keyPrefix}-table-${pIdx}`} className="overflow-x-auto my-3 block clear-both">
            {isJournal && (
              <div className="text-[10px] font-mono font-bold tracking-wider text-forest print:text-black mb-1 uppercase">
                [FINANCIAL JOURNAL BOOK — 5-COLUMN FORMAT]
              </div>
            )}
            {isLedger && (
              <div className="text-[10px] font-mono font-bold tracking-wider text-forest print:text-black mb-1 uppercase">
                [T-ACCOUNT FINANCIAL LEDGER]
              </div>
            )}
            <table className="min-w-full border-collapse border border-gray-300 text-xs font-mono text-left bg-white print:border-black shadow-xs">
              <thead className="bg-gray-100 print:bg-gray-100/90 border-b-2 border-gray-300 print:border-black font-heading font-bold text-gray-900">
                <tr>
                  {headers.map((h, hIdx) => {
                    const isAmountCol = /debit|credit|amount|rs|balance|\(₹\)|\(rs\)/i.test(h);
                    return (
                      <th
                        key={hIdx}
                        className={`border border-gray-300 print:border-black px-3 py-1.5 ${
                          isAmountCol ? 'text-right' : 'text-center'
                        }`}
                      >
                        <MathText text={h} as="span" />
                      </th>
                    );
                  })}
                </tr>
              </thead>
              <tbody>
                {dataRows.map((row, rIdx) => {
                  const isTotalRow = row.some((cell) => /total|balance\s*c\/d|balance\s*b\/d/i.test(cell));
                  return (
                    <tr
                      key={rIdx}
                      className={
                        isTotalRow
                          ? 'border-b-4 border-double border-gray-900 font-bold bg-gray-50 print:bg-transparent print:border-black'
                          : rIdx % 2 === 1
                          ? 'bg-gray-50/70 print:bg-transparent'
                          : 'bg-white'
                      }
                    >
                      {row.map((cell, cIdx) => {
                        const hName = headers[cIdx] || '';
                        const isAmountCol = /debit|credit|amount|rs|balance|\(₹\)|\(rs\)/i.test(hName);
                        return (
                          <td
                            key={cIdx}
                            className={`border border-gray-300 print:border-black px-3 py-1.5 align-middle ${
                              isAmountCol ? 'text-right font-mono' : 'text-left'
                            }`}
                          >
                            <MathText text={cell} as="span" />
                          </td>
                        );
                      })}
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        );
      }
    }

    return <React.Fragment key={`${keyPrefix}-txt-${pIdx}`}>{part}</React.Fragment>;
  });
}

/**
 * Component to seamlessly render mixed text, inline LaTeX ($...$, \(...\)),
 * block LaTeX ($$...$$, \[...\]), code snippets, and standalone math expressions.
 */
export const MathText: React.FC<MathTextProps> = ({
  text,
  className = '',
  as: Component = 'span',
  block = false,
  dir = 'auto',
}) => {
  const renderedContent = useMemo(() => {
    if (!text) return null;

    // Check if the text contains any LaTeX indicators: delimiters or backslashes
    const hasDelimiters = /(\$\$[\s\S]*?\$\$|\$[^\$]+?\$|\\\[[\s\S]*?\\\]|\\\([^\)]+?\\\))/.test(text);
    const hasLatexCommands = /\\[a-zA-Z]+|\^\{|_\{/.test(text);
    const hasCodeBlocks = /```|`[^`\n]+?`/.test(text);
    const hasMarkdownTable = /\|[^\n]+\|/.test(text);

    // If completely plain text with no math indicators, code blocks, or tables, return raw text
    if (!hasDelimiters && !hasLatexCommands && !hasCodeBlocks && !hasMarkdownTable) {
      return text;
    }

    // If whole string is wrapped in display math delimiters or block mode is requested for entire math string
    if (block && !hasDelimiters && hasLatexCommands && !hasCodeBlocks) {
      const html = renderKatexHtml(text, true);
      return <div className="katex-display-container my-2 overflow-x-auto" dangerouslySetInnerHTML={{ __html: html }} />;
    }

    // Split text by common math delimiters:
    // 1. $$...$$ (Display mode)
    // 2. \[...\] (Display mode)
    // 3. $...$ (Inline mode)
    // 4. \(...\) (Inline mode)
    const tokens = text.split(/(\$\$[\s\S]*?\$\$|\\\[[\s\S]*?\\\]|\$[^\$\n]+?\$|\\\([^\)]+?\\\))/g);

    return tokens.map((token, index) => {
      if (!token) return null;

      // Display math $$...$$
      if (token.startsWith('$$') && token.endsWith('$$') && token.length >= 4) {
        const math = token.slice(2, -2);
        const html = renderKatexHtml(math, true);
        return (
          <span
            key={`math-disp-${index}`}
            className="katex-block-wrapper block my-1.5 overflow-x-auto text-center"
            dangerouslySetInnerHTML={{ __html: html }}
          />
        );
      }

      // Display math \[...\]
      if (token.startsWith('\\[') && token.endsWith('\\]') && token.length >= 4) {
        const math = token.slice(2, -2);
        const html = renderKatexHtml(math, true);
        return (
          <span
            key={`math-disp-bracket-${index}`}
            className="katex-block-wrapper block my-1.5 overflow-x-auto text-center"
            dangerouslySetInnerHTML={{ __html: html }}
          />
        );
      }

      // Inline math $...$
      if (token.startsWith('$') && token.endsWith('$') && token.length >= 2) {
        const math = token.slice(1, -1);
        const html = renderKatexHtml(math, false);
        return (
          <span
            key={`math-inline-${index}`}
            className="katex-inline-wrapper inline-block align-baseline"
            dangerouslySetInnerHTML={{ __html: html }}
          />
        );
      }

      // Inline math \(...\)
      if (token.startsWith('\\(') && token.endsWith('\\)') && token.length >= 4) {
        const math = token.slice(2, -2);
        const html = renderKatexHtml(math, false);
        return (
          <span
            key={`math-inline-paren-${index}`}
            className="katex-inline-wrapper inline-block align-baseline"
            dangerouslySetInnerHTML={{ __html: html }}
          />
        );
      }

      // If token itself contains raw unescaped LaTeX formula commands without delimiters (e.g. \frac{1}{2})
      if (/\\[a-zA-Z]{2,}/.test(token) && !token.includes('\n')) {
        const html = renderKatexHtml(token, false);
        return (
          <span
            key={`math-raw-${index}`}
            className="katex-inline-wrapper inline-block align-baseline"
            dangerouslySetInnerHTML={{ __html: html }}
          />
        );
      }

      // Regular text segment with code block and markdown table parsing
      return renderTextWithMarkdownElements(token, `seg-${index}`);
    });
  }, [text, block]);

  return <Component className={className} dir={dir}>{renderedContent}</Component>;
};
